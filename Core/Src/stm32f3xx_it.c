/* USER CODE BEGIN 1 */
void EXTI3_IRQHandler(void)
{
    // Check if 50 ms has passed since the last state change (of any edge)
    if ((system_ticks - last_interrupt_time) > 50)
    {
        // If the time has passed, check that the button is actually pressed (low level on PA3)
        if ((GPIOA->IDR & (1 << 3)) == 0)
        {
            GPIOA->ODR ^= (1 << 4);
        }
    }

    // Be sure to update the time on EVERY interrupt (every bounce).
    last_interrupt_time = system_ticks;

    // Clearing Flags
    EXTI->PR = (1 << 3);

    __DSB();
    __ISB();
}
